// ---------- helpers ----------
const FONT = "Arial";

function P(text, opts = {}) {
  return new Paragraph({
    spacing: { after: 120 },
    ...opts,
    children: Array.isArray(text)
      ? text
      : [new TextRun({ text, font: FONT, ...(opts.run || {}) })],
  });
}

function H1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 360, after: 200 },
    pageBreakBefore: true,
    children: [new TextRun({ text, font: FONT, bold: true, size: 32 })],
  });
}

function H2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 280, after: 160 },
    children: [new TextRun({ text, font: FONT, bold: true, size: 26 })],
  });
}

function H3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 200, after: 120 },
    children: [new TextRun({ text, font: FONT, bold: true, size: 22 })],
  });
}

function bullet(text, level = 0) {
  return new Paragraph({
    numbering: { reference: "bullets", level },
    spacing: { after: 80 },
    children: [new TextRun({ text, font: FONT, size: 22 })],
  });
}

function num(text, level = 0) {
  return new Paragraph({
    numbering: { reference: "numbers", level },
    spacing: { after: 80 },
    children: [new TextRun({ text, font: FONT, size: 22 })],
  });
}

function bold(text) {
  return new TextRun({ text, font: FONT, bold: true, size: 22 });
}
function plain(text) {
  return new TextRun({ text, font: FONT, size: 22 });
}

function note(text) {
  return new Paragraph({
    spacing: { before: 120, after: 120 },
    border: {
      left: { style: BorderStyle.SINGLE, size: 18, color: "2E75B6", space: 8 },
    },
    indent: { left: 240 },
    children: [
      new TextRun({ text: "Важно: ", font: FONT, bold: true, size: 22, color: "2E75B6" }),
      new TextRun({ text, font: FONT, size: 22 }),
    ],
  });
}

const border = { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" };
const borders = { top: border, bottom: border, left: border, right: border };

function cell(text, opts = {}) {
  const { bold: b = false, fill, width = 4680 } = opts;
  return new TableCell({
    borders,
    width: { size: width, type: WidthType.DXA },
    shading: fill ? { fill, type: ShadingType.CLEAR } : undefined,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [
      new Paragraph({
        children: [new TextRun({ text, font: FONT, bold: b, size: 22 })],
      }),
    ],
  });
}

function twoColTable(headers, rows, widths = [3000, 6360]) {
  return new Table({
    width: { size: widths[0] + widths[1], type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((h, i) =>
          cell(h, { bold: true, fill: "D5E8F0", width: widths[i] })
        ),
      }),
      ...rows.map(
        r =>
          new TableRow({
            children: r.map((c, i) => cell(c, { width: widths[i] })),
          })
      ),
    ],
  });
}

